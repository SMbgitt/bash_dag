def add_code_block(doc, code_text):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = tbl.rows[0].cells[0]
    cell.width = Cm(16.5)
    set_cell_border(cell, 
                    top=dict(val='single', sz=6, color='CCCCCC'),
                    bottom=dict(val='single', sz=6, color='CCCCCC'),
                    left=dict(val='single', sz=6, color='CCCCCC'),
                    right=dict(val='single', sz=6, color='CCCCCC'))
    set_cell_shading(cell, "F9F9F9")
    
    p = cell.paragraphs[0]
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.0
    
    run = p.add_run(code_text)
    run.font.name = "Consolas"
    run.font.size = Pt(8.5)
    
    post_p = doc.add_paragraph()
    post_p.paragraph_format.space_before = Pt(0)
    post_p.paragraph_format.space_after = Pt(6)

